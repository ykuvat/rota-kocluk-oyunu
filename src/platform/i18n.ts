const dicts = { tr, en } as const;
export type Locale = keyof typeof dicts;

let locale: Locale = "tr";

export const setLocale = (l: Locale) => (locale = l);
export const getLocale = () => locale;
export const t = (key: MessageKey): string => dicts[locale][key];
const extra = { tr: EXTRA_TR, en: EXTRA_EN } as const;

/** Dinamik anahtarlar için (ör. "day.3"); bilinmeyen anahtar olduğu gibi döner. */
export const tk = (key: string): string => (key in tr ? t(key as MessageKey) : (extra[locale][key] ?? extra.tr[key] ?? key));
/** {ad} biçimli yer tutucuları doldurur. */
export const tf = (key: string, vars: Record<string, string | number>): string =>
  tk(key).replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
